def inject():
    total_added = 0
    for rel_path, entries_map in keywords_map.items():
        full_path = os.path.join(r"d:\Personalise\Homemad\Lorebook\Nasuverse", rel_path.replace("/", "\\"))
        if not os.path.exists(full_path):
            print(f"Warning: File not found: {full_path}")
            continue
            
        with open(full_path, "r", encoding="utf-8") as f:
            lorebook = json.load(f)
            
        file_added = 0
        for entry_idx_str, kw in entries_map.items():
            if entry_idx_str in lorebook["entries"]:
                entry = lorebook["entries"][entry_idx_str]
                # Inject keys
                existing_keys = entry.get("key", [])
                for k in kw.get("key", []):
                    if k not in existing_keys:
                        existing_keys.append(k)
                        file_added += 1
                entry["key"] = existing_keys
                
                # Inject secondary keys
                existing_sec = entry.get("keysecondary", [])
                for ks in kw.get("keysecondary", []):
                    if ks not in existing_sec:
                        existing_sec.append(ks)
                        file_added += 1
                entry["keysecondary"] = existing_sec
                
        with open(full_path, "w", encoding="utf-8") as f:
            json.dump(lorebook, f, ensure_ascii=False, indent=2)
            
        print(f"Updated {rel_path}: added {file_added} Thai keys.")
        total_added += file_added
        
    print(f"\nCompleted! Total Thai keys added across 8 files: {total_added}")

if __name__ == "__main__":
    inject()

